export const ICON_NAMES = Object.keys(MAP);

/**
 * Decorative icon (always next to a text label, so aria-hidden).
 * `name` is the old ligature string from the section data.
 */
export function LigIcon({ name, className }) {
  const C = MAP[name] || TriangleAlert;
  return <C className={className} aria-hidden="true" strokeWidth={2} />;
}

